function toSVG(grid) {
  let rects = '';
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      let run = 0;
      while (row[x + run] === '#') run++;
      rects += `<rect x="${x}" y="${y}" width="${run}" height="1"/>`;
      x += run;
    }
  });
  return `<svg viewBox="0 0 16 16" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}

export const DEPT_ICON = Object.fromEntries(Object.entries(G).map(([k, g]) => [k, toSVG(g)]));
export const deptIcon = (slug) => DEPT_ICON[slug] || DEPT_ICON.other;
